"""Cross-reference a board's run-tests.py results with a host baseline of the same version.

    python3 crossref.py results/esp32_bytecode.json results/esp32_native_via_mpy.json \
                        --baseline results/unix_v1.29.0_baseline.json > RESULTS.md

A test that fails on the board AND on the unix port built from the same tag is
version skew: the test suite (taken from master) checks behaviour that changed
after that tag. A test that fails on the board but passes on the unix build of
the same version is the interesting kind: specific to the port or the hardware.

Input files are the ``_results.json`` that run-tests.py writes into its result
directory; each entry is ``[test, pass|fail|skip|ignored, reason]``.
"""

import argparse
import collections
import json
import os


def load(path):
    with open(path) as f:
        d = json.load(f)
    return d['args'], {r[0]: (r[1], r[2]) for r in d['results']}


def counts(table):
    c = collections.Counter(v[0] for v in table.values())
    return c['pass'] + c['fail'], c['pass'], c['fail'], c['skip']


def label(args):
    bits = [args.get('build') or args.get('platform') or '?']
    if args.get('via_mpy'):
        bits.append('--via-mpy')
    if args.get('emit') and args['emit'] != 'bytecode':
        bits.append('--emit ' + args['emit'])
    return ' '.join(bits)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('board', nargs='+', help='_results.json from the board runs')
    ap.add_argument('--baseline', required=True, help='_results.json from the unix port, same version')
    ap.add_argument('--title', default='Upstream test suite on a board vs. the unix port of the same version')
    a = ap.parse_args()

    base_args, base = load(a.baseline)
    runs = [(p, *load(p)) for p in a.board]

    out = []
    out.append('# ' + a.title)
    out.append('')
    out.append('Generated by `crossref.py` from the `_results.json` files in `results/`.')
    out.append('')
    out.append('## Summary')
    out.append('')
    out.append('| Run | Performed | Passed | Failed | Skipped |')
    out.append('|---|---|---|---|---|')
    for p, args, table in runs:
        out.append('| `{}` ({}) | {} | {} | {} | {} |'.format(os.path.basename(p), label(args), *counts(table)))
    out.append('| `{}` ({}, baseline) | {} | {} | {} | {} |'.format(
        os.path.basename(a.baseline), label(base_args), *counts(base)))
    out.append('')

    for p, args, table in runs:
        name = os.path.basename(p)
        fails = sorted(t for t, v in table.items() if v[0] == 'fail')
        out.append('## `{}`: {} failures'.format(name, len(fails)))
        out.append('')
        groups = collections.OrderedDict((
            ('Also fail on the unix port of the same version (version skew)', []),
            ('Pass on the unix port of the same version: **specific to this port or board**', []),
            ('Not comparable (skipped or absent on the unix port)', []),
        ))
        for t in fails:
            b = base.get(t)
            if b and b[0] == 'fail':
                groups[list(groups)[0]].append(t)
            elif b and b[0] == 'pass':
                groups[list(groups)[1]].append(t)
            else:
                groups[list(groups)[2]].append('{} (unix: {})'.format(t, b[0] if b else 'not run'))
        for g, items in groups.items():
            if items:
                out.append('**{}** ({})'.format(g, len(items)))
                out.append('')
                out.extend('- `{}`'.format(t) for t in items)
                out.append('')

        skips = [t for t, v in table.items() if v[0] == 'skip']
        by_dir = collections.Counter(t.split('/')[0] for t in skips)
        out.append('{} skipped, by directory: {}'.format(
            len(skips), ', '.join('{} {}'.format(d, n) for d, n in sorted(by_dir.items()))))
        out.append('')

    if len(runs) == 2:
        (_, _, t1), (_, _, t2) = runs
        only2 = sorted(t for t in t2 if t2[t][0] == 'skip' and t1.get(t, ('',))[0] == 'pass')
        if only2:
            out.append('## Skipped only in `{}` ({} tests that pass in `{}`)'.format(
                os.path.basename(runs[1][0]), len(only2), os.path.basename(runs[0][0])))
            out.append('')
            out.extend('- `{}`'.format(t) for t in only2)
            out.append('')

    print('\n'.join(out))


if __name__ == '__main__':
    main()
